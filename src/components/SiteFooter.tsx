import { Moment } from './Moment';
import { dataAsOfMoment } from '@/lib/freshness';

/**
 * Подвал страницы: и юридическая строка, и момент данных.
 *
 * ## Почему момент данных здесь, а не в заголовке
 *
 * Момент — это ответ на вопрос «насколько свежёе то, что я вижу», и он должен
 * быть на каждой странице, а не на одной из них. Подвал — единственное место,
 * которое есть у каждой страницы, поэтому момент живёт здесь.
 *
 * ## Откуда берётся момент
 *
 * Страница передаёт подвалу `dataAsOf` того ответа, который сама отрисовала:
 * у страницы каталога — момент её данных, у карточки товара — момент данных
 * этого товара. Подвал ничего не запрашивает сам: иначе он показывал бы
 * момент, которого страница не показывает, — а это ровно тот обман, который
 * задача закрывает.
 *
 * ## Про закешированные страницы
 *
 * Страницы категорий и товаров кешируются на минуту (`revalidate = 60`), и
 * вместе с ними кешируется и этот момент. Показывать «сейчас» было бы
 * неправдой: показанные данные старше на ту минуту, на которую закеширована
 * страница. Поэтому подвал показывает именно тот момент, который пришёл в
 * ответе, — старый он или нет.
 */
export function SiteFooter({ dataAsOf }: { dataAsOf?: string | null }) {
  const moment = dataAsOfMoment(dataAsOf ?? null);

  return (
    // `role="contentinfo"` — потому что подвал теперь рисует страница, а не
    // макет: внутри `<main>` нативный `<footer>` не становится ориентиром
    // `contentinfo`, а ориентир на странице должен быть один.
    <footer role="contentinfo" className="mt-12 border-t border-slate-200 bg-white">
      <div className="container-page py-6 text-sm text-slate-500">
        <p>
          Витрина читает базу краулера в режиме&nbsp;только&nbsp;чтение и ничего в ней не изменяет.
          Цены и кэшбэк — на момент последнего обхода каталога.
        </p>
        <p className="mt-1 text-xs text-slate-400">
          Данные принадлежат их владельцам. Проект не связан с операторами источника.
        </p>
        <p className="mt-2 text-xs text-slate-500">
          {moment.label} <Moment moment={moment} />
        </p>
      </div>
    </footer>
  );
}
