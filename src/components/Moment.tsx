import type { PageMoment } from '@/lib/freshness';

/**
 * Момент на странице: текст для глаза и `datetime` для машины.
 *
 * ## Зачем это отдельный компонент
 *
 * Момент показывается в двух местах — в подвале и в блоке счётчиков, — и в
 * обоих он обязан выглядеть одинаково и означать одно и то же. Функция,
 * повторённая в двух компонентах, разъедется при первом же изменении: в одном
 * месте появится прочерк, в другом останется «Invalid Date».
 *
 * ## Почему `<time>`, а не просто текст
 *
 * `<time datetime="…">` — это семантика, а не украшение: по атрибуту машина
 * знает, что перед ней момент, и может его разобрать. Текст внутри остаётся
 * человеческим — «21.10.2026, 14:03», — потому что машине нужен разбор, а
 * человеку нужно читать.
 *
 * ## Почему без момента нет и `<time>`
 *
 * Момента нет — значит нет и элемента: `<time>` без `datetime` не значит
 * ничего, а момент «сейчас» был бы враньём. Поэтому на месте отсутствующего
 * момента стоит прочерк.
 */
export function Moment({ moment }: { moment: PageMoment }) {
  if (!moment.dateTime) return <>{moment.text}</>;

  return <time dateTime={moment.dateTime}>{moment.text}</time>;
}
