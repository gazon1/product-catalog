/**
 * Моменты, которые витрина показывает посетителю.
 *
 * ## Два разных момента — и почему их нельзя путать
 *
 * Краулер отвечает на два разных вопроса, и отвечает двумя разными полями:
 *
 *   - `dataAsOf` — **момент данных**: когда витрину последний раз обходили.
 *     Это то, что показывают как «данные на …»;
 *   - `asOf` — **момент чтения кэша** агрегатов: когда счётчики посчитали.
 *     Это не свежесть данных, это «счётчики посчитаны в …».
 *
 * Разница между ними — это разница между «когда это было записано» и «когда
 * это посчитали». Подписать `asOf` как «данные на …» — значит сказать
 * посетителю, что данные свежие на момент чтения кэша, а это неправда: кэш
 * живёт десять минут, и данные за это время могли устареть.
 *
 * Поэтому здесь не одно слово «момент» и не один формат, а две отдельные
 * функции — `dataAsOfMoment` и `countersAsOfMoment`. Каждая из них знает и
 * поле, и его подпись, и подпись зашита в саму функцию: подписать `asOf` как
 * «данные на …» нельзя уже потому, что для этого есть другая функция, а
 * слова у них разные.
 *
 * ## Почему время местное, а не UTC
 *
 * Момент приходит от краулера в UTC, а читает его человек. Витрина рендерится
 * на сервере, поэтому «местное время пользователя» — это часовой пояс сервера:
 * `Intl` без заданной зоны печатает именно его. На сервере в московской зоне
 * посетитель видит московское время, и «данные на 21.10.2026, 14:03» означает
 * «14:03 по Москве», а не четырнадцать часов ночи в его часовом поясе.
 *
 * ## Почему пустое значение — это «—», а не «сейчас»
 *
 * Контракт делает `dataAsOf` необязательным: краулер, который старше контракта,
 * его не присылает, и каталог, в котором ещё ничего не записано, отдаёт
 * `null`. Оба случая значат одно: **момента нет**. Печатать в этом месте
 * «сейчас» — значит сказать посетителю, что данные только что обошли, когда
 * про них ничего не известно. Поэтому пустое значение рисуется прочерком, и
 * страница не притворяется свежей.
 */

/** Значение, когда момента нет: краулер старше контракта или каталог пуст. */
export const NO_MOMENT = '—';

/** Подпись момента данных: «данные на …». */
export const DATA_AS_OF_LABEL = 'Данные на';

/** Подпись момента чтения кэша счётчиков: «счётчики посчитаны в …». */
export const COUNTERS_AS_OF_LABEL = 'Счётчики посчитаны в';

/**
 * Момент на странице: подпись, текст и значение для `datetime`.
 *
 * Три части одного смысла. Подпись объясняет, что за момент показан, текст
 * читается человеком, а `dateTime` разбирается машиной.
 */
export interface PageMoment {
  /** Подпись, которая объясняет, что это за момент. */
  readonly label: string;
  /** Текст для глаза: дата и время, либо прочерк, когда момента нет. */
  readonly text: string;
  /** Значение для атрибута `datetime`; `null`, когда момента нет. */
  readonly dateTime: string | null;
}

/**
 * Разобрать момент из ответа краулера.
 *
 * Пустая строка и `null` — это не момент, а его отсутствие, и разбирать их
 * нечем: `new Date('')` — это Invalid Date, а `new Date(null)` — это 1970 год,
 * и оба выглядели бы как настоящее время. Поэтому отсутствие отсекается
 * здесь, а не в форматтере.
 */
export function parseMoment(iso: string | null | undefined): Date | null {
  if (typeof iso !== 'string') return null;
  const trimmed = iso.trim();
  if (trimmed === '') return null;

  const parsed = new Date(trimmed);
  return Number.isNaN(parsed.getTime()) ? null : parsed;
}

/**
 * Момент так, как его читает человек: дата и время в местном времени сервера.
 *
 * `timeZone` передаётся только в тестах — production-значение намеренно
 * оставлено пустым, чтобы страница печатала время того сервера, который её
 * отдал.
 */
export function formatMoment(iso: string | null | undefined, timeZone?: string): string {
  const parsed = parseMoment(iso);
  if (!parsed) return NO_MOMENT;

  const options: Intl.DateTimeFormatOptions = {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    hourCycle: 'h23',
  };
  if (timeZone) options.timeZone = timeZone;

  return new Intl.DateTimeFormat('ru-RU', options).format(parsed);
}

/**
 * Значение для атрибута `dateTime` элемента `<time>`.
 *
 * Это момент в ISO-8601 (UTC) — так его понимает машина. Текст рядом с ним
 * остаётся местным, а атрибут — однозначным: иначе «21.10.2026, 14:03» без
 * зоны означал бы разное в разных часовых поясах.
 *
 * Момента нет — значит нет и атрибута: `<time>` без `datetime` не имеет
 * смысла, и пустой элемент лучше, чем элемент с выдуманным значением.
 */
export function momentDateTime(iso: string | null | undefined): string | null {
  const parsed = parseMoment(iso);
  return parsed ? parsed.toISOString() : null;
}

/**
 * Момент данных: «данные на …».
 *
 * Собирает подпись и значение в один объект, чтобы страница не могла
 * нарисовать значение одной подписью, а подпись — от другого поля.
 */
export function dataAsOfMoment(iso: string | null | undefined): PageMoment {
  return {
    label: DATA_AS_OF_LABEL,
    text: formatMoment(iso),
    dateTime: momentDateTime(iso),
  };
}

/**
 * Момент чтения кэша счётчиков: «счётчики посчитаны в …».
 *
 * Отдельная функция, а не флаг у `dataAsOfMoment`: подписи у двух моментов
 * разные слова, и смешать их — значит соврать посетителю о свежести данных.
 */
export function countersAsOfMoment(iso: string | null | undefined): PageMoment {
  return {
    label: COUNTERS_AS_OF_LABEL,
    text: formatMoment(iso),
    dateTime: momentDateTime(iso),
  };
}
