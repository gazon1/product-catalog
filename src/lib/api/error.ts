/**
 * Словарь сбоя: то, чем все части клиента описывают неудачу.
 *
 * ## Почему это отдельный файл
 *
 * Ошибка — не собственность ни одной из частей клиента: транспорт выбрасывает её
 * при таймауте и при отказе соединения, повтор — когда решает, что повторять
 * нельзя, разбор ответа — когда ответа `2xx` не случилось. Общий тип ошибки,
 * который принадлежит всем троим и никому, иначе пришлось бы выбирать: тип
 * ошибки в модуле транспорта сделал бы транспорт владельцем того, чем пользуются
 * ещё двое.
 *
 * ## Ключ
 *
 * Ключ читается из окружения и отправляется в заголовке `X-Api-Key`. Он никогда
 * не попадает в логи, никогда не попадает в сообщение об ошибке и никогда не
 * попадает в URL: URL оказывается в логах доступа, в логе прокси и в отчёте о
 * падении, а ключ, попавший в любое из этих мест, — это ключ, который придётся
 * ротировать. `redact()` — это пояс для подтяжек: даже ошибка, в тексте которой
 * ключ уже был, не сможет его выпустить.
 */

/**
 * Неудачный вызов каталогового API.
 *
 * `status` — HTTP-код ответа, который API всё-таки дал, и `0` для сбоя,
 * случившегося раньше ответа: отказа соединения, таймаута, ошибки DNS. Поэтому
 * `401` отличается от таймаута уже по одному коду — именно это и нужно
 * обработчику ошибок: `401` означает неверный ключ (ошибка развёртывания),
 * таймаут означает, что краулер медленный или лежит.
 */
export class ApiError extends Error {
  /** HTTP-код, либо `0`, когда ответа не было вовсе. */
  readonly status: number;

  /** Разобранное тело ответа, когда оно было. */
  readonly body: unknown;

  /** Запрошенный путь. Никогда не содержит ключа. */
  readonly path: string;

  /**
   * Идентификатор, по которому оператор найдёт запись в журнале краулера.
   *
   * Идентификатор краулера, когда краулер ответил, — это тот самый, под которым
   * он и записал запрос, — и собственный идентификатор сайта, когда не ответил:
   * тогда это единственная ручка, которая есть у обеих сторон. `null`, если
   * сбой случился раньше, чем запрос вообще был сделан (например, не задан базовый
   * адрес).
   */
  readonly requestId: string | null;

  /**
   * Был ли сбой дедлайном, а не ответом.
   *
   * Различие решает, стоит ли запрос повторить: запрос, истёкший по времени,
   * ничего не говорит о самом запросе, поэтому его можно спросить снова, а
   * запрос, на который ответили и отказали, — нельзя.
   */
  readonly timedOut: boolean;

  constructor(
    message: string,
    options: {
      status?: number;
      body?: unknown;
      path?: string;
      cause?: unknown;
      requestId?: string | null;
      timedOut?: boolean;
    } = {},
  ) {
    super(message, options.cause !== undefined ? { cause: options.cause } : undefined);
    this.name = 'ApiError';
    this.status = options.status ?? 0;
    this.body = options.body;
    this.path = options.path ?? '';
    this.requestId = options.requestId ?? null;
    this.timedOut = options.timedOut ?? false;
  }
}

/** Ключ, как он есть прямо сейчас, — без проверки на пустоту. */
export function apiSecret(): string {
  return (process.env.CRAWLER_API_KEY ?? '').trim();
}

/**
 * Убрать ключ из сообщения.
 *
 * Ключ не попадает в сообщение намеренно, поэтому здесь не должно меняться
 * ничего. Он нужен потому, что «не должен» — это ещё не «не может»: ошибка,
 * брошенная рантаймом или прокси, может нести текст, который писали не мы, а
 * единственная строка, которая не должна покидать этот процесс, — это ключ.
 */
export function redact(message: string, secret: string): string {
  if (!secret) return message;
  return message.split(secret).join('[redacted]');
}

/**
 * Что рантайм сказал под причиной сбоя.
 *
 * `fetch` сообщает об отказе соединения словом «fetch failed» и хранит настоящую
 * причину (`connect ECONNREFUSED 127.0.0.1:8099`) в `cause`. Причина — это ровно
 * то, что нужно оператору, и то, что узнаёт собственное сопоставление ошибок
 * сайта, — поэтому она несётся в сообщение, а не теряется.
 */
export function causeDetail(err: unknown): string {
  if (!(err instanceof Error)) return 'unknown error';
  const cause = (err as { cause?: unknown }).cause;
  if (cause instanceof Error && cause.message) return `${err.message} (${cause.message})`;
  return err.message;
}
