/**
 * Повтор: когда спросить ещё раз.
 *
 * ## Что здесь решается
 *
 * Один вопрос: **стоит ли спросить снова** — и если стоит, то через сколько.
 * Модуль ничего не знает ни о том, как устроен запрос (`transport.ts`), ни о
 * том, какие параметры в него класть (`params.ts`), ни о том, как читать ответ
 * (`response.ts`).
 *
 * ## Почему повтор вообще есть
 *
 * Повторяются ровно два сбоя — те, что ничего не говорят о самом запросе.
 *
 * `503` — это краулер говорит «каталог сейчас не отдаётся»: база перезапускается,
 * запрос упёрся в таймаут краулера, проверка готовности отвечает «нет». Запрос
 * был правильным; момент был неудачным. Спросить снова через мгновение — это
 * разница между страницей, которая отрисовалась, и страницей с ошибкой.
 *
 * Таймаут — тот же самый сбой, увиденный с другой стороны: краулер не ответил вовремя,
 * а это утверждение о краулере, а не о запросе.
 *
 * ## Почему повтор ровно один
 *
 * Повтор — это запрос, о котором вызывающий не просил, и он стоит базе краулера
 * ещё одного запроса. Один повтор превращает неудачный момент в работающую
 * страницу; два превращают лежащий краулер в троекную нагрузку — ровно
 * противоположное тому, для чего повтор и нужен.
 *
 * ## Почему `4xx` не повторяется никогда
 *
 * `4xx` — это краулер говорит «этот запрос неверен»: неверный ключ, параметр,
 * который нельзя истолковать, URL, которого нет. Второй попыткой запрос был бы
 * неверен ровно так же, и она удвоила бы трафик того, кто зовёт со сломанным
 * ключом. `429` — то же самое: краулер попросил подождать, и ответ на это
 * находится в заголовке `Retry-After`, а не в том, чтобы спросить снова немедленно.
 * `429` — это ответ, и вызывающий вправе его увидеть.
 */

import { ApiError } from './error';
import { request, type ApiRequestOptions, type RawAnswer } from './transport';

/**
 * Сколько раз пробуют запрос.
 *
 * Два — это один повтор: первая попытка и ещё одна.
 */
const MAX_ATTEMPTS = 2;

/**
 * Дольше названного момента ждать нельзя.
 *
 * Серверу, который назвал момент, верят — но не без границы: вызывающий здесь
 * это отрисовка страницы, а страница, висящая минуту из-за чужого `Retry-After`,
 * хуже страницы с ошибкой. Десять секунд — это ровно один бюджет запроса;
 * более долгое ожидание не купит ничего, чего не купила бы вторая попытка.
 */
export const RETRY_AFTER_MAX_MS = 10_000;

/**
 * Ожидание, когда ответ не назвал момента.
 *
 * `503` без `Retry-After` всё равно значит «не сейчас», и спросить снова в ту же
 * миллисекунду — значит спросить снова, пока краулер всё ещё говорит «нет».
 */
export const RETRY_AFTER_DEFAULT_MS = 1_000;

/**
 * Откат после таймаута.
 *
 * Таймаут говорит, что краулер медленный, а не что его нет: запрос, который он
 * выполнял, может всё ещё выполняться. Второй запрос в ту же миллисекунду
 * добавляет давления ровно тогда, когда сервис уже под ним.
 */
export const TIMEOUT_RETRY_BACKOFF_MS = 250;

/**
 * Ожидание между двумя попытками.
 *
 * Шов существует ради того, чтобы ожидание можно было доказать без теста,
 * который действительно ждёт: набор, который спит по две секунды на случай, и
 * медленный, а случай, который измеряет настоящую задержку, падает на
 * загруженной машине, а не на изменении в клиенте. По умолчанию здесь настоящий
 * таймер, и в работающем сайте его никто не подменяет.
 */
export const sleeper = {
  /** Подождать указанное число миллисекунд. */
  wait(ms: number): Promise<void> {
    return new Promise((resolve) => {
      setTimeout(resolve, ms);
    });
  },
};

/**
 * Ожидание с дрожанием.
 *
 * Полное дрожание: случайная доля вычисленного ожидания, а не оно само. Иначе
 * отказанные в один момент вызывающие повторили бы строго в общем ритме и
 * ударили по краулеру ещё одной волной — той же волной, но чуть позже.
 */
function jitter(delayMs: number): number {
  return Math.floor(Math.random() * delayMs);
}

/**
 * Названный ответом момент, в миллисекундах.
 *
 * Краулер присылает число секунд до того, как можно попробовать снова, поэтому
 * заголовок — это задержка, а не метка времени. Всё остальное — нет заголовка
 * вовсе, дата, слово — момента не называет, и вызывающий берёт ожидание по
 * умолчанию.
 */
export function retryAfterMs(header: string | null): number | null {
  if (header === null) return null;
  const text = header.trim();
  if (text === '') return null;

  const seconds = Number(text);
  if (!Number.isFinite(seconds) || seconds < 0) return null;

  return Math.min(Math.floor(seconds * 1000), RETRY_AFTER_MAX_MS);
}

/**
 * Сделать один GET и при необходимости спросить ещё раз.
 *
 * ## Что повторяется
 *
 * Два сбоя и только два.
 *
 * `503` — краулер говорит «каталог сейчас не отдаётся»: база перезапускается,
 * запрос упёрся в таймаут краулера, проверка готовности отвечает «нет». Запрос
 * был правильным; момент был неудачным. Спросить снова через мгновение — это
 * разница между страницей, которая отрисовалась, и страницей с ошибкой.
 *
 * Таймаут — тот же самый сбой с другой стороны: краулер не ответил вовремя, а
 * это утверждение о краулере, а не о запросе.
 *
 * ## Почему вторая попытка ждёт
 *
 * Спросить снова в ту же миллисекунду — значит спросить снова, пока краулер всё
 * ещё говорит «нет». Когда ответ называет момент, с которого его можно спросить
 * снова, — заголовок `Retry-After`, — этот момент и есть ожидание: это
 * собственное слово сервера о том, сколько длится его отказ, и клиент,
 * который его игнорирует, превращает один отказ в два отказа в один момент.
 *
 * Ожидание дрожащее: задержка — случайная доля вычисленного ожидания, а не оно
 * само, потому что отказанные в один момент вызывающие иначе повторили бы
 * строго в общем ритме и ударили по краулеру ещё одной волной.
 *
 * Ответ, который не назвал момента, всё равно получает короткую паузу вместо
 * немедленного второго вопроса, а таймаут — собственный короткий откат: таймаут
 * значит, что краулер, возможно, ещё работает, и второй запрос в ту же
 * миллисекунду добавляет давления ровно тогда, когда сервис уже медленный.
 *
 * Ожидание ограничено сверху. Вызывающий не должен висеть минуту из-за того,
 * что сервер так сказал.
 *
 * ## Что не повторяется
 *
 * `4xx` — краулер говорит «этот запрос неверен»: неверный ключ, параметр,
 * который нельзя истолковать, URL, которого нет. Второй попыткой запрос был бы
 * неверен ровно так же, и она удвоила бы трафик того, кто зовёт со сломанным
 * ключом. `429` — то же самое: краулер попросил подождать, и ответ на это
 * находится в заголовке `Retry-After`, а не в том, чтобы спросить снова немедленно.
 * `429` — это ответ, и вызывающий вправе его увидеть — и поэтому `429` здесь не
 * повторяется, сколько бы его `Retry-After` ни просил подождать.
 *
 * Сетевой сбой — соединение отказали, хоста нет — тоже не повторяется. Краулера
 * там нет, и вторая попытка застала бы его там же; вызывающему честная ошибка
 * полезнее запроса, который вдвое дольше падает так же.
 *
 * ## Почему повтор ровно один
 *
 * Повтор — это запрос, о котором вызывающий не просил, и он стоит базе краулера
 * ещё одного запроса. Один повтор превращает неудачный момент в работающую
 * страницу; два превращают лежащий краулер в троекную нагрузку — ровно
 * противоположное тому, для чего повтор и нужен.
 */
export async function requestWithRetry(
  path: string,
  options: ApiRequestOptions = {},
): Promise<RawAnswer> {
  for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt += 1) {
    try {
      const answer = await request(path, options);

      if (answer.status === 503 && attempt < MAX_ATTEMPTS) {
        // Краулер ответил и сказал «не сейчас». Через мгновение он вполне может
        // сказать «да», и это единственный код, ради которого такой вопрос стоит.
        await sleeper.wait(jitter(retryAfterMs(answer.retryAfter) ?? RETRY_AFTER_DEFAULT_MS));
        continue;
      }

      return answer;
    } catch (err) {
      // Таймаут стоит ещё одного вопроса; отказ с ответом — нет.
      if (err instanceof ApiError && err.timedOut && attempt < MAX_ATTEMPTS) {
        await sleeper.wait(jitter(TIMEOUT_RETRY_BACKOFF_MS));
        continue;
      }
      throw err;
    }
  }

  // Сюда управление не доходит: цикл заканчивается либо ответом, либо ошибкой.
  throw new Error('the retry loop ended without an answer');
}
