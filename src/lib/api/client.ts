/**
 * Клиент каталога: точка входа для витрины.
 *
 * ## Что это за файл
 *
 * Небольшая обёртка над `fetch` без зависимостей, которая знает три вещи, о
 * которых остальному сайту знать не придётся: где API, как к нему
 * авторизоваться и сколько его ждать. Всё остальное — какой эндпоинт, какие
 * параметры — принадлежит `queries.ts`.
 *
 * ## Четыре решения — четыре файла
 *
 * Клиент отвечает на четыре разных вопроса, и раньше он отвечал на все четыре
 * в одном файле. Теперь у каждого вопроса свой файл, и у каждого — свой тест:
 *
 *   - `transport.ts` — **как спросить**: адрес, ключ, заголовки, дедлайны;
 *   - `params.ts` — **что спросить**: строка запроса в словаре API;
 *   - `retry.ts` — **когда спросить ещё раз**: какие сбои стоят второй попытки
 *     и сколько ждать перед ней;
 *   - `response.ts` — **как прочитать ответ**: тело, разобранное в структуру,
 *     и сбой, превращённый в ошибку.
 *
 * ## Ключ
 *
 * Ключ читается из окружения и отправляется как `X-Api-Key`. Он никогда не
 * попадает в логи, никогда не попадает в сообщение об ошибке и никогда не
 * попадает в URL: URL оказывается в логах доступа, в логе прокси и в отчёте о
 * падении, а ключ, попавший в любое из этих мест, — это ключ, который придётся
 * ротировать.
 *
 * ## Два дедлайна
 *
 * `CONNECT_TIMEOUT_MS` ограничивает время до прихода *заголовков* ответа: три
 * секунды. Это бюджет на соединение — время, чтобы добраться до краулера и
 * получить начало ответа.
 *
 * `REQUEST_TIMEOUT_MS` ограничивает запрос целиком, вместе с телом: десять
 * секунд. Он заведомо **больше** собственного восьмисекундного таймаута
 * SQL-запроса краулера, чтобы запрос, упёршийся в этот таймаут, приходил
 * собственной ошибкой краулера — `5xx` с пояснением, — а не обрывался здесь и не
 * выглядел как сетевой сбой. Это разные инциденты: «каталог слишком медленный» и
 * «каталог недоступен» — не одно и то же, и оператор должен уметь их различать.
 *
 * ## Идентификатор запроса
 *
 * Каждый вызов несёт идентификатор собственный, отправляет его в `X-Request-Id`,
 * а краулер отвечает тем же идентификатором. Смысл — корреляция: «каталог ответил
 * 503» — это симптом, а «каталог ответил 503 на запрос 7f3c…» — это симптом,
 * который оператор найдёт в журнале краулера и увидит, какой запрос упал, сколько
 * он шёл и что краулер с ним сделал.
 *
 * ## Что остаётся здесь
 *
 * Этот файл — шов между частями: имена, которыми пользуется витрина, остаются
 * здесь, поэтому страница, импортирующая `apiGet`, продолжает работать, как бы
 * части ни переставлялись.
 */

