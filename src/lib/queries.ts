/**
 * Всё, что витрина читает из каталога.
 *
 * ## Граница
 *
 * Краулер владеет базой, и единственный вход в неё — его HTTP API только для
 * чтения. Этот файл — сторона витрины на этой границе: он превращает словарь
 * сайта (фильтр, сортировка, страница) в запрос и превращает ответ обратно в
 * те формы, которые рисуют страницы.
 *
 * SQL здесь больше нет, и строки подключения тоже нет, и драйвера нет. В этом
 * и был смысл перемены: витрина, которая не может открыть соединение с базой,
 * не может сломать схему краулера, не может случайно в неё записать и не может
 * продолжать «работать» со схемой, которую переименовала миграция.
 *
 * ## Что всё ещё принадлежит сайту
 *
 * Две вещи, и обе — те, которые API не может решить за нас:
 *
 *   - **словарь сортировки** — имена в `?sort=` — это наши собственные URL,
 *     поэтому сайт проверяет их до того, как они поедут
 *     (`src/lib/api/sort.ts`);
 *   - **заглушка заголовка** — контракт обещает непустой заголовок, но карточка
 *     без заголовка не может быть нарисована ссылкой, а пустой якорь невидим,
 *     поэтому сайт держит собственную заглушку.
 *
 * Всё остальное — схема, единицы внутри базы, SQL, экранирование поискового
 * запроса — принадлежит краулеру.
 *
 * ## Что внутри
 *
 * Два решения, разделённые по смыслу, а не по длине файла:
 *
 *   - `catalog/mapping.ts` — **как прочитать ответ**: привести его к формам,
 *     которые рисуют страницы;
 *   - `catalog/requests.ts` — **что спросить**: какой эндпоинт, с какими
 *     параметрами и с каким бюджетом времени.
 *
 * Этот файл остаётся швом, через который читает витрина: имена, которыми
 * пользуются страницы, не изменились, поэтому ни одна страница не двинулась.
 */

