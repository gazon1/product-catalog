/**
 * Сканер исходников, на котором стоят архитектурные гейты.
 *
 * ## Зачем это отдельный файл
 *
 * Гейты проверяют разные правила, и у каждого правила свой файл тестов. Но все
 * они смотрят на исходники одинаково: сначала вырезают комментарии, потом
 * гасят содержимое строковых литералов, потом ищут. Общие шаги живут здесь, а
 * не копируются в каждый гейт: скопированный сканер — это сканер, который
 * однажды разъедется с оригиналом, и гейт, который молча перестанет видеть
 * половину нарушений.
 *
 * ## Что здесь нет
 *
 * Здесь нет ни одного утверждения: это инструмент гейтов, а не гейт.
 */

import { readFileSync, readdirSync } from 'node:fs';
import { resolve } from 'node:path';

/** Корень исходников витрины. */
export const SRC = resolve(__dirname, '..', '..', 'src');

/** Прочитать исходник по его пути на диске. */
export function read(file: string): string {
  return readFileSync(file, 'utf8');
}

/**
 * Вырезать комментарии перед поиском SQL-ключей.
 *
 * Гейт на запись когда-то искал по сырому файлу, вместе с прозой, и срабатывал
 * на этой фразе в `queries.ts`: «a typed second *copy* of the projection». `COPY`
 * — это пишущий SQL-оператор, а «copy» в английском комментарии — нет, и
 * доступное тогда исправление было переписать комментарий. Это неправильное
 * исправление для гейта: оно делает гейт зелёным, меняя то, что он
 * обследует, и следующий автор должен знать про ловушку вместо того, чтобы
 * код был в безопасности сам по себе.
 *
 * Тот же класс дефекта уже нашли и починили на стороне краулера, где
 * проверка подключения обязана пропускать комментарии ровно по этой причине.
 * Два репозитория, поддерживающих один контракт, не должны расходиться во
 * мнении о том, является ли комментарий кодом.
 *
 * `//`, которому предшествует `:`, — не комментарий: это `//` в URL внутри
 * строкового литерала, и трактовка его как комментария молча обрезала бы
 * остаток строки — а в остатке строки может прятаться настоящая запись.
 */
export function stripComments(source: string): string {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/(^|[^:])\/\/.*$/gm, '$1');
}

/**
 * Погасить содержимое простых строковых и регулярных литералов.
 *
 * Гейту нужно отличать *код* от *текста*, а это не одно и то же:
 *
 *   - `import { Pool } from 'pg'` — драйвер базы, и токен живёт в строковом
 *     литерале;
 *   - `className="truncate text-xs"` — утилита Tailwind, и она тоже живёт в
 *     строковом литерале;
 *   - `hint="В базе краулера нет ни одной записи в crawl_targets"` — фраза,
 *     которую читает посетитель, и токен тоже живёт в строковом литерале.
 *
 * Гейт не может срабатывать на первом и молчать на втором, поэтому проверки
 * идут по разным источникам:
 *
 *   - **токены соединения** ищутся с литералами на месте — строка подключения
 *     внутри строкового литерала всё равно строка подключения;
 *   - **имена схемы** и **пишущие операторы** ищутся по источнику с погашенными
 *     литералами, потому что имя таблицы в предложении — не запрос. Шаблонные
 *     литералы *не* гасятся: SQL в этом репозитории пишется в обратных
 *     кавычках, и именно в шаблонном литерале он и спрятался бы.
 *
 * Вырезание комментариев идёт первым, поэтому ключевое слово в комментарии
 * исчезает до того, как сработает хоть одна проверка.
 */
export function blankPlainLiterals(source: string): string {
  let out = '';
  let i = 0;

  /** Начинается ли в этой позиции регулярное выражение, а не деление. */
  const startsRegex = (): boolean => {
    const before = out.replace(/\s+$/, '').slice(-1);
    if (before === '') return true;
    return '(,=:[!&|?{};+-*%~^<>'.includes(before);
  };

  while (i < source.length) {
    const ch = source[i]!;

    if (ch === '/' && source[i + 1] === '/') {
      while (i < source.length && source[i] !== '\n') i += 1;
      continue;
    }

    if (ch === '/' && source[i + 1] === '*') {
      const end = source.indexOf('*/', i + 2);
      i = end === -1 ? source.length : end + 2;
      continue;
    }

    // Шаблонный литерал сохраняется: именно в нём писался бы SQL.
    if (ch === '`') {
      const start = i;
      i += 1;
      while (i < source.length) {
        if (source[i] === '\\') {
          i += 2;
          continue;
        }
        if (source[i] === '`') {
          i += 1;
          break;
        }
        i += 1;
      }
      out += source.slice(start, i);
      continue;
    }

    if (ch === "'" || ch === '"') {
      const quote = ch;
      i += 1;
      while (i < source.length) {
        if (source[i] === '\\') {
          i += 2;
          continue;
        }
        if (source[i] === quote) {
          i += 1;
          break;
        }
        i += 1;
      }
      out += ' ';
      continue;
    }

    if (ch === '/' && startsRegex()) {
      i += 1;
      let inClass = false;
      while (i < source.length) {
        const c = source[i]!;
        if (c === '\\') {
          i += 2;
          continue;
        }
        if (c === '[') inClass = true;
        else if (c === ']') inClass = false;
        else if (c === '/' && !inClass) {
          i += 1;
          break;
        } else if (c === '\n') break;
        i += 1;
      }
      out += ' ';
      continue;
    }

    out += ch;
    i += 1;
  }

  return out;
}

/** Каждый исходный файл под `src/`, рекурсивно. */
export function sourceFiles(dir = SRC): string[] {
  const files: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = resolve(dir, entry.name);
    if (entry.isDirectory()) files.push(...sourceFiles(full));
    else if (/\.(ts|tsx)$/.test(entry.name)) files.push(full);
  }
  return files;
}

/** Путь файла относительно `src/` — чтобы сообщение об ошибке было читаемым. */
export function relative(file: string): string {
  return file.slice(SRC.length + 1);
}
