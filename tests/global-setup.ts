/**
 * Жизненный цикл прогона: то, что vitest зовёт как global setup и teardown.
 *
 * ## Зачем этот файл такой тонкий
 *
 * Прогон состоит из нескольких решений, и каждое из них живёт в своём файле
 * под `tests/contract/`: документ контракта, образ, контейнер, окружение.
 * Здесь остаётся только последовательность: что вызывается, в каком порядке и
 * что из этого уходит рабочим процессам.
 *
 * Такое разделение нужно не ради длины файла, а ради одного свойства: у
 * каждого решения свой владелец, и изменение одного не тащит за собой
 * остальные. Диагностика неудачного старта контейнера — это правка одного
 * файла, а не того, где настраивается прогон.
 *
 * ## Что было раньше и почему это важнее, чем кажется
 *
 * Набор когда-то поднимал контейнер PostgreSQL, накатывал миграции краулера
 * из *копии*, лежавшей в `dev/db/`, сеял из второй копии — а потом витрина
 * спрашивала эту базу своим собственным SQL. Копия была слабым местом:
 * миграция краулера, переименовавшая колонку, оставляла оба репозитория
 * зелёными и давала пустую витрину в продакшене. Витрина проверяла свой SQL
 * против схемы, которую сама же и разветвила.
 *
 * Теперь краулер работает контейнером, накатывает миграции и сеет сам, а
 * витрина говорит с ним по HTTP через свои публичные функции. Копии схемы в
 * этом репозитории больше нет, и SQL — тоже: витрина не может разойтись со
 * схемой, потому что схему она никогда не видит.
 *
 * ## Отсутствие Docker — это провал, а не пропуск
 *
 * Если до демона не достучаться, настройка бросает исключение. Набор,
 * который отчитывается об успехе, ничего не выполнив, хуже, чем набора нет
 * вовсе: это зелёная сборка, не проверившая ничего, — ровно тот дефект,
 * против которого работает весь этот репозиторий.
 *
 * ## Отсутствующий образ краулера — это провал контрактного теста, а не всех
 *
 * Образ краулера — отдельный артефакт, собираемый другим репозиторием.
 * Когда его нет, *контрактный* тест падает с сообщением, в котором сказано
 * ровно, какого образа не хватает и как его получить, — а остальной набор
 * всё равно идёт. Это не пропуск: файл падает громко, и код возврата это
 * говорит. Юнит-тесты, архитектурный гейт и проверка типов краулера не
 * требуют, и прятать их за отсутствующим артефактом значило бы затруднить
 * различение «контракт не держится» и «окружение не готово».
 *
 * ## Значения передаются файлом
 *
 * Базовый адрес и ключ уходят к рабочим процессам файлом, а не переменной
 * окружения: `globalSetup` vitest работает в главном процессе, а тесты — в
 * рабочих, и переменная окружения, поставленная в первом, не обязана
 * дойти до вторых. Файл прочитать могут оба.
 *
 * Файл пишется за пределами репозитория. Очевидное место —
 * `node_modules/.vitest-...` — кладёт в дерево, за которым vitest следит,
 * файл, меняющийся от прогона к прогону, а это верный способ закончить
 * открытыми файловыми дескрипторами на выходе. Временный каталог не
 * отслеживается, и он в любом случае убирается при завершении.
 *
 * ## Бюджет готовности наш, и наша же диагностика
 *
 * Стратегия ожидания testcontainers по умолчанию ждёт, пока порт контейнера
 * будет занят, и сдаётся через 60 секунд, выбрасывая собственное «Port 8080
 * not bound after 60000ms». Это сообщение неверно дважды: краулеру ниже
 * дают две минуты, поэтому чужой срок срабатывает первым, и причина, по
 * которой краулер медленный — или причина, по которой он умер, — в
 * собственном логе краулера, которого чужое сообщение не показывает.
 *
 * Поэтому контейнер запускается без ожидания порта, готовность опрашивается
 * на нашем бюджете, а неудача говорит, что именно произошло: контейнер
 * вышел (с его кодом возврата и логом), контейнер жив и просто не ответил в
 * срок (это таймаут, а не неверный образ), либо образ отвечает, но не
 * отдаёт каталог (404 или 401). Всё это — в `tests/contract/container.ts`.
 */

import { assertDockerIsAvailable, startCrawler, stopCrawler } from './contract/container';
import { removeHandoff, writeHandoff } from './contract/environment';
import { ensureImageIsPresent, imageIdOf, resolveCrawlerImage } from './contract/image';

// Публичная поверхность прежняя: пять тестовых файлов импортируют эти три
// функции именно отсюда, и переносить их к новым файлам — значит править
// пять файлов ради того, чтобы не менять один. Повторный экспорт держит путь
// импорта прежним.
export { loadContractDocument, parseContractDocument, buildValidator } from './contract/document';
export { resolveCrawlerImage } from './contract/image';
export { contractEnvironmentPath } from './contract/environment';
export type { ContractEnvironment } from './contract/environment';

/**
 * Поднять окружение прогона и передать его рабочим процессам.
 *
 * Порядок здесь — часть поведения: без Docker нет ничего, образ нужен раньше
 * контейнера, а передача значений — последнее, потому что она обязана
 * случиться и тогда, когда краулер не поднялся. Именно в этом случае файл
 * передачи и несёт причину.
 */
export default async function setup(): Promise<void> {
  assertDockerIsAvailable();

  const image = resolveCrawlerImage();
  const pullProblem = ensureImageIsPresent(image);
  const imageId = imageIdOf(image);

  if (imageId === null) {
    // Образ — отдельный артефакт другого репозитория. Его отсутствие —
    // это провал контрактного теста, с сообщением о том, что делать, — а
    // остальной набор всё равно идёт.
    //
    // Сюда же приходит то, что сказало о себе скачивание: анонимное
    // скачивание, отклонённое реестром из-за часового лимита, — это другая
    // проблема, нежели отсутствующий образ, и читателю надо сказать, какая
    // именно.
    writeHandoff({
      apiUrl: null,
      apiKey: null,
      image,
      imageId: null,
      containerId: null,
      postgresUri: null,
      error:
        `the crawler image "${image}" is not available locally. Pull it (docker pull ` +
        `"${image}"), build it in the crawler repository (just app::docker-build), or ` +
        `point the suite at another one: CONTRACT_CRAWLER_IMAGE=<image> npm test` +
        (pullProblem !== null ? `\n\n${pullProblem}` : ''),
    });
    console.log(`\n  ⚠ the crawler image "${image}" is not available — the contract test will fail\n`);
    return;
  }

  const run = await startCrawler(image);

  writeHandoff({
    apiUrl: run.apiUrl,
    apiKey: run.apiKey,
    image,
    imageId,
    containerId: run.containerId,
    postgresUri: run.postgresUri,
    error: run.error,
  });

  if (run.outcome === 'not-started') {
    console.log(`\n  ⚠ the crawler container could not be started — the contract test will fail\n`);
  } else if (run.error !== null) {
    console.log(`\n  ⚠ the crawler is not ready — the contract test will fail\n`);
  } else {
    console.log(`\n  crawler: ${image} (${imageId}) on ${run.apiUrl}\n`);
  }
}

/** Остановить контейнеры прогона и убрать файл передачи. */
export async function teardown(): Promise<void> {
  await stopCrawler();
  removeHandoff();
}
