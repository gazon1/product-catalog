#!/usr/bin/env bash
#
# Значение переменной — из окружения, а если его там нет, из `.env`.
#
# ## Зачем это отдельным файлом
#
# Адрес каталога и ключ нужны в двух местах — в `just dev` и в `stack-up.sh`, —
# и оба места должны читать их одинаково. Копия правила чтения в двух файлах
# разъезжается тихо: одно место начинает снимать кавычки, другое — нет, и
# витрина получает `401` только у того, кто запускал через другой рецепт.
#
# ## Кавычки
#
# Деплой пишет значения в одинарных кавычках: compose читает такое значение
# буквально, и `$` в ключе не переписывается по дороге. Кавычки — не часть
# значения, поэтому `read_env` их снимает.
#
# Подключается как источник (`source scripts/read-env.sh`), после чего
# доступна функция `read_env ИМЯ`.
#
# ENV_FILE — путь к файлу с переменными; по умолчанию `.env` в корне
# репозитория.

ENV_FILE="${ENV_FILE:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/.env}"

read_env() {
    local name="$1"
    local value="${!name:-}"
    if [ -z "$value" ] && [ -f "$ENV_FILE" ]; then
        value="$(grep -E "^${name}=" "$ENV_FILE" 2>/dev/null | head -1 | cut -d= -f2- || true)"
    fi
    case "$value" in
        \'*\') value="${value:1:${#value}-2}" ;;
    esac
    printf '%s' "$value"
}
